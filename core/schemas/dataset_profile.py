"""Dataset Profile schemas for AutoDS AI Studio.

Strongly-typed Pydantic models for deterministic dataset profiling and
structured AI dataset analysis.
"""

from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, Field


class ColumnProfile(BaseModel):
    """Profile statistics for a single dataset column."""

    name: str
    dtype: str
    pandas_dtype: str
    non_null_count: int
    missing_count: int
    missing_percentage: float
    unique_count: int
    unique_percentage: float
    is_numeric: bool = False
    is_categorical: bool = False
    is_datetime: bool = False
    is_boolean: bool = False
    is_constant: bool = False
    is_possible_id: bool = False
    is_high_cardinality: bool = False

    # Semantic Datatype Inference (Section 3 & 4)
    inferred_semantic_type: Optional[str] = None
    sample_values: List[Any] = Field(default_factory=list)
    suspicious_values: List[Any] = Field(default_factory=list)
    format_patterns: List[str] = Field(default_factory=list)
    possible_datatype: Optional[str] = None
    datatype_confidence: float = 1.0
    datatype_evidence: List[str] = Field(default_factory=list)

    # Numeric statistics
    min_val: Optional[Union[float, int, str]] = None
    max_val: Optional[Union[float, int, str]] = None
    mean_val: Optional[float] = None
    median_val: Optional[float] = None
    std_val: Optional[float] = None
    standard_deviation: Optional[float] = None
    q1_val: Optional[float] = None
    q3_val: Optional[float] = None

    # Categorical statistics (top values: value -> count)
    top_values: Optional[Dict[str, int]] = None
    top_value_counts: Optional[Dict[str, int]] = None
    cardinality: Optional[int] = None

    # Datetime statistics
    min_date: Optional[str] = None
    max_date: Optional[str] = None

    @property
    def null_count(self) -> int:
        """Alias for missing_count."""
        return self.missing_count

    @property
    def null_percentage(self) -> float:
        """Alias for missing_percentage."""
        return self.missing_percentage


class DatasetQualityIssue(BaseModel):
    """Quality issue detected deterministically by Python."""

    issue_type: str
    column: Optional[str] = None
    severity: Literal["low", "medium", "high", "critical"] = "medium"
    description: str
    metric_value: Optional[str] = None


class DatasetProfile(BaseModel):
    """Complete deterministic dataset profile generated by Python."""

    filename: Optional[str] = "dataset.csv"
    row_count: int
    column_count: int
    duplicate_row_count: int
    duplicate_row_percentage: float
    memory_usage_mb: float
    quality_score: float = Field(default=100.0, ge=0.0, le=100.0)
    quality_status: str = "Good"  # "Excellent", "Good", "Fair", "Poor", "Critical"

    columns: List[ColumnProfile] = Field(default_factory=list)
    missing_columns: List[str] = Field(default_factory=list)
    constant_columns: List[str] = Field(default_factory=list)
    possible_id_columns: List[str] = Field(default_factory=list)
    high_cardinality_columns: List[str] = Field(default_factory=list)
    suspicious_columns: List[str] = Field(default_factory=list)
    mixed_type_columns: List[str] = Field(default_factory=list)

    detected_issues: List[DatasetQualityIssue] = Field(default_factory=list)
    profiled_at: str = ""


class DetectedIssue(BaseModel):
    """AI-interpreted data quality issue with evidence requirement."""

    issue_type: str
    column: Optional[str] = None
    severity: Literal["low", "medium", "high", "critical"]
    explanation: str
    evidence: str
    recommendation: str


class DatasetAIAnalysis(BaseModel):
    """Structured AI understanding and interpretation of a DatasetProfile."""

    dataset_summary: str
    likely_domain: str
    important_columns: List[str] = Field(default_factory=list)
    quality_assessment: str
    detected_issues: List[DetectedIssue] = Field(default_factory=list)
    priority_issues: List[str] = Field(default_factory=list)
    recommended_next_steps: List[str] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    confidence_score: float = Field(default=0.85, ge=0.0, le=1.0)
    confidence_level: str = "High"  # "High", "Medium", "Low"
